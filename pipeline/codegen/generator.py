    return "\n".join(
        [
            "fastapi>=0.115.0",
            "uvicorn[standard]>=0.30.0",
            "sqlalchemy>=2.0.30",
            "pydantic>=2.8.0",
            "httpx>=0.27.0",
            "pytest>=8.2.0",
            "",
        ]
    )


