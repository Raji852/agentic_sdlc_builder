def _services(features: dict[str, Any]) -> str:
    has_alias = bool(features.get("custom_alias"))
    has_rate = bool(features.get("rate_limit"))

    create_sig = "db: Session, long_url: str, custom_alias: str | None = None, rate_limit_per_minute: int = 60"
    if has_alias:
        allocate_block = '''
    code = custom_alias
    if code:
        if not ALIAS_RE.match(code):
            raise HTTPException(status_code=400, detail="Invalid custom alias")
        if db.query(ShortURL).filter((ShortURL.code == code) | (ShortURL.custom_alias == code)).first():
            raise HTTPException(status_code=409, detail="Alias already in use")
    else:
        code = None
        for _ in range(8):
            candidate = generate_code()
            if not db.query(ShortURL).filter(ShortURL.code == candidate).first():
                code = candidate
                break
        if not code:
            raise HTTPException(status_code=500, detail="Unable to allocate short code")
'''
    else:
        allocate_block = '''
    code = None
    for _ in range(8):
        candidate = generate_code()
        if not db.query(ShortURL).filter(ShortURL.code == candidate).first():
            code = candidate
            break
    if not code:
        raise HTTPException(status_code=500, detail="Unable to allocate short code")
'''

    rate_arg = "rate_limit_per_minute=rate_limit_per_minute," if has_rate else ""
    alias_arg = "custom_alias=custom_alias," if has_alias else ""

    return f'''from __future__ import annotations

import re
import secrets
import string
from urllib.parse import urlparse

from fastapi import HTTPException
from sqlalchemy.orm import Session

from app.models import ClickEvent, ShortURL

CODE_ALPHABET = string.ascii_letters + string.digits
ALIAS_RE = re.compile(r"^[A-Za-z0-9_-]{{3,32}}$")
BLOCKED_HOSTS = {{"localhost", "127.0.0.1", "0.0.0.0"}}


def generate_code(length: int = 7) -> str:
    return "".join(secrets.choice(CODE_ALPHABET) for _ in range(length))


def validate_target_url(url: str) -> None:
    parsed = urlparse(url)
    if parsed.scheme not in {{"http", "https"}}:
        raise HTTPException(status_code=400, detail="Only http/https URLs are allowed")
    host = (parsed.hostname or "").lower()
    if host in BLOCKED_HOSTS:
        raise HTTPException(status_code=400, detail="Local/private targets are not allowed")


def create_short_url({create_sig}) -> ShortURL:
    validate_target_url(long_url)
{allocate_block}
    row = ShortURL(
        code=code,
        long_url=long_url,
        {alias_arg}
        {rate_arg}
    )
    db.add(row)
    db.commit()
    db.refresh(row)
    return row


def resolve_and_track(db: Session, code: str, user_agent: str | None = None) -> ShortURL:
    row = db.query(ShortURL).filter(ShortURL.code == code, ShortURL.is_active.is_(True)).first()
    if not row:
        raise HTTPException(status_code=404, detail="Short URL not found")
    row.click_count += 1
    db.add(ClickEvent(code=code, user_agent=(user_agent or "")[:512] or None))
    db.commit()
    db.refresh(row)
    return row


def get_metadata(db: Session, code: str) -> ShortURL:
    row = db.query(ShortURL).filter(ShortURL.code == code).first()
    if not row:
        raise HTTPException(status_code=404, detail="Short URL not found")
    return row


def get_analytics(db: Session, code: str, limit: int = 10) -> dict:
    row = get_metadata(db, code)
    events = (
        db.query(ClickEvent)
        .filter(ClickEvent.code == code)
        .order_by(ClickEvent.clicked_at.desc())
        .limit(limit)
        .all()
    )
    return {{
        "code": row.code,
        "long_url": row.long_url,
        "click_count": row.click_count,
        "recent_clicks": [
            {{"clicked_at": e.clicked_at.isoformat(), "user_agent": e.user_agent}} for e in events
        ],
    }}
'''


def _main(app_name: str, features: dict[str, Any]) -> str:
    has_alias = bool(features.get("custom_alias"))
    has_rate = bool(features.get("rate_limit"))

    create_args = ["db", "long_url=str(payload.url)"]
    if has_alias:
        create_args.append("custom_alias=payload.custom_alias")
    if has_rate:
        create_args.append("rate_limit_per_minute=payload.rate_limit_per_minute")
    create_call = ",\n        ".join(create_args)

    resp_extra = ""
    if has_alias:
        resp_extra += "\n        custom_alias=getattr(row, 'custom_alias', None),"
    if has_rate:
        resp_extra += "\n        rate_limit_per_minute=getattr(row, 'rate_limit_per_minute', 60),"

    return f'''from __future__ import annotations

from contextlib import asynccontextmanager

from fastapi import Depends, FastAPI, Request
from fastapi.responses import RedirectResponse
from sqlalchemy.orm import Session

from app import services
from app.database import get_db, init_db
from app.schemas import AnalyticsResponse, HealthResponse, URLCreate, URLResponse


@asynccontextmanager
async def lifespan(_: FastAPI):
    init_db()
    yield


app = FastAPI(title="{app_name}", version="1.0.0", lifespan=lifespan)


def to_response(row, request: Request) -> URLResponse:
    base = str(request.base_url).rstrip("/")
    return URLResponse(
        code=row.code,
        short_url=f"{{base}}/{{row.code}}",
        long_url=row.long_url,
        created_at=row.created_at,
        click_count=row.click_count,{resp_extra}
    )


@app.get("/health", response_model=HealthResponse)
def health():
    return HealthResponse(status="ok", service="url-shortener")


@app.post("/api/v1/urls", response_model=URLResponse, status_code=201)
def create_url(payload: URLCreate, request: Request, db: Session = Depends(get_db)):
    row = services.create_short_url(
        {create_call}
    )
    return to_response(row, request)


@app.get("/api/v1/urls/{{code}}", response_model=URLResponse)
def get_url(code: str, request: Request, db: Session = Depends(get_db)):
    return to_response(services.get_metadata(db, code), request)


@app.get("/api/v1/urls/{{code}}/analytics", response_model=AnalyticsResponse)
def analytics(code: str, db: Session = Depends(get_db)):
    return services.get_analytics(db, code)


@app.get("/{{code}}")
def redirect(code: str, request: Request, db: Session = Depends(get_db)):
    if code in {{"docs", "openapi.json", "redoc", "health", "api"}}:
        return {{"detail": "Not a short code"}}
    row = services.resolve_and_track(db, code, user_agent=request.headers.get("user-agent"))
    return RedirectResponse(url=row.long_url, status_code=307)
'''


