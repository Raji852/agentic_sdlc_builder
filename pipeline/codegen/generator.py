from __future__ import annotations

"""Implementation agent codegen — writes a real URL shortener project from a design spec."""

from pathlib import Path
from typing import Any


def generate_url_shortener(project_dir: Path, spec: dict[str, Any]) -> list[str]:
    """Generate a runnable FastAPI URL shortener into project_dir. Returns relative file paths."""
    project_dir.mkdir(parents=True, exist_ok=True)
    features = spec.get("features", {})
    app_name = spec.get("app_name", "Generated URL Shortener")

    files: dict[str, str] = {
        "requirements.txt": _requirements(),
        "README.md": _readme(app_name, features, spec),
        "app/__init__.py": '"""Generated URL shortener application."""\n',
        "app/database.py": _database(),
        "app/models.py": _models(features),
        "app/schemas.py": _schemas(features),
        "app/services.py": _services(features),
        "app/main.py": _main(app_name, features),
        "tests/__init__.py": "",
        "tests/test_app.py": _tests(features),
        "tests/test_edge_cases.py": _edge_tests(features),
    }

    written: list[str] = []
    for rel, content in files.items():
        path = project_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(rel)
    return written


